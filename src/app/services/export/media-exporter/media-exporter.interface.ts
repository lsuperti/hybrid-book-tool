import { XmlElement } from '../xml/xml-builder';
import { ExportFileEntry } from '../text-exporter/text-exporter.interface';
import { MediaFile } from '../../media-files/media-files';

/**
 * A media segment associated with a specific hybrid book phrase ID.
 */
export interface CorrelatedMediaPhrase<TSegment> {
  phraseId: number,
  segment: TSegment,
}

/**
 * Information describing a hybrid book media presentation set.
 */
export interface HybridBookSetDefinition {
  title: string,
  mediaGroup: string,
}

/**
 * Context provided to media format exporters.
 */
export interface MediaExportContext<TSegment = unknown> {
  phrases: readonly CorrelatedMediaPhrase<TSegment>[],
  mediaFiles: readonly MediaFile[],
  groupName: string,
}

/**
 * Result data generated by a media exporter.
 */
export interface MediaExportResult {
  mediaElement: XmlElement,
  files: ExportFileEntry[],
  setDefinition: HybridBookSetDefinition,
}

/**
 * Extensible contract for media format exporters (video, audio, etc.).
 */
export interface MediaFormatExporter<TSegment = unknown> {
  readonly mediaType: string,
  readonly defaultGroupName: string,
  readonly defaultSetTitle: string,

  /**
   * Exports media phrases into a media XML description and zip file entries.
   *
   * @param context The media export context.
   * @returns A promise resolving to the media export result.
   */
  exportMedia(context: MediaExportContext<TSegment>): Promise<MediaExportResult>,
}
